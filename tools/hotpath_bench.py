#!/usr/bin/env python3
"""Emit (and optionally run) the hot-path micro-benchmark.

The capture hot path's own numbers belong in CI, not on a phone: every
change that touches Log.luau, the interceptors, or the row renderer should
be able to show what it costs.  This test pins the two behaviors that keep
a spammy game playable:

  * DeepClone is *bounded* - a hostile payload (a very deep chain or a very
    wide table) is cut off at the clone budget and shares references beyond
    it, while ordinary argument packs are still cloned field-for-field;
  * the capture loop stays cheap per call, with timings printed so a
    regression shows up as a number instead of a hunch.

Structural properties are asserted; timings are printed (not gated) except
for one generous ceiling on the adversarial clone, which used to run for
seconds inside a hook.

Usage:
  python3 tools/hotpath_bench.py            # write build/hotpath_bench.luau
  LUAU=/path/to/luau python3 tools/hotpath_bench.py --run
"""
from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LOG_SOURCE = ROOT / "src" / "Utils" / "Log.luau"
OUTPUT = ROOT / "build" / "hotpath_bench.luau"

